"""Turn the cached agent runs into honest numbers. Reads data/cache/base and writes docs/eval_results.md.
Every number comes from real runs: nothing here is estimated.
Usage: python3 eval/report.py
"""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
files = sorted((ROOT / "data" / "cache" / "base").glob("*.json"))
rows = [json.loads(f.read_text()) | {"_f": f.stem} for f in files]
n = len(rows)
if not n:
    raise SystemExit("no cached runs found; run scripts/pregenerate.py first")

first = sum(1 for r in rows if r["attempts"] == 1 and not r["used_fallback"])
rewr = sum(1 for r in rows if 1 < r["attempts"] and not r["used_fallback"])
fall = sum(1 for r in rows if r["used_fallback"])
drafts = sum(len(r["catches"]) + (0 if r["used_fallback"] else 1) for r in rows)
bad_drafts = sum(len(r["catches"]) for r in rows)
kinds = Counter(p["kind"] for r in rows for c in r["catches"] for p in c["problems"])
cases = Counter()
for r in rows:
    for c in r["catches"]:
        for p in c["problems"]:
            cases[(p["kind"], p["reason"].split(":")[0][:60])] += 1
by_match = Counter(r["_f"].split("__")[0] for r in rows)
views = list((ROOT / "data" / "cache" / "views").glob("*.json"))
rej = sum(1 for v in views if json.loads(v.read_text()).get("notes"))

md = f"""# Evaluation results

Generated by `eval/report.py` from the cached agent runs in `data/cache`. Nothing here is estimated.

## Fact check loop (Narrator, Fact Checker)
| Measure | Value |
|---|---|
| Moments narrated | {n} across {len(by_match)} matches |
| Passed on the first draft | {first} ({100*first/n:.0f}%) |
| Fixed after the checker rejected a draft | {rewr} ({100*rewr/n:.0f}%) |
| Fell back to the safe template after 3 failed drafts | {fall} ({100*fall/n:.0f}%) |
| Total drafts written by the Narrator | {drafts} |
| Drafts the checker rejected | {bad_drafts} ({100*bad_drafts/drafts:.0f}% of all drafts) |

**What this means.** A single agent with no checker would have shipped every one of those rejected drafts. In these runs
{100*bad_drafts/drafts:.0f}% of the Narrator's drafts contained at least one problem that code or the reviewer caught,
and {100*(n-first)/n:.0f}% of moments needed at least one correction before they were safe to show.

## What was caught
| Problem type | Count |
|---|---|
""" + "\n".join(f"| {k} | {v} |" for k, v in kinds.most_common()) + f"""

Types: `claim` is a number or event that failed recomputation, `wording` is a rule violation (digits in prose, banned
words, bad placeholders), `causal` is a cause no detector supports, `unsupported` is flagged by the AI reviewer.

Most common specific reasons:

""" + "\n".join(f"- {c}x {k[0]}: {k[1]}" for k, c in cases.most_common(8)) + f"""

## Persona and translation steps
{len(views)} persona and language views were generated. {rej} of them had a rewrite rejected at least once and kept the
previous wording (see the `notes` field in each cached view).

## Not measured here
- Whether the commentary is good football writing. That needs human readers.
- Recall of the AI reviewer: it can miss an unsupported phrase, and the word filter only covers English.
- Pressure detector against hidden truth, measured separately on 40 simulated matches: it found 63% of real high press
  periods, about 44% of its alerts were real, and it gave 1.2 false alerts per match. It is labelled "pressure rise".
"""
out = ROOT / "docs" / "eval_results.md"
out.parent.mkdir(exist_ok=True)
out.write_text(md)
print(md)
